#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { apiRoutePolicies, routeHasMutation } from "../server/route-policies.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "docs/api-reference.md");

function routeExpression(policy) {
  if (policy.path) return `\`${policy.path}\``;
  if (policy.paths) return policy.paths.map((entry) => `\`${entry}\``).join("<br>");
  if (policy.prefix) return `\`${policy.prefix}/…\``;
  if (policy.pattern) return `\`${String(policy.pattern).replaceAll("|", "\\|")}\``;
  return "invalid";
}

const authDescriptions = {
  none: "Public route; no caller identity.",
  optional: "Session is used when present, but anonymous access is allowed.",
  session: "Valid Task Node browser session required.",
  bearer: "Valid terminal bearer session required.",
  oauth_state: "Single-use, provider-bound OAuth state required.",
  webhook_secret: "Configured webhook secret required.",
  admin_bearer: "Configured administrative bearer token required.",
  handler: "The route handler enforces its context-specific session/wallet policy.",
};

function bodyDescription(policy) {
  if (!routeHasMutation(policy)) return "—";
  const label = (body) => `${body.schema?.allowUnknown === false ? "strict" : "provider-shaped"} JSON ≤ ${body.maxBytes} bytes`;
  if (policy.body) return label(policy.body);
  if (policy.bodies) {
    return Object.entries(policy.bodies)
      .map(([method, body]) => `${method}: ${label(body)}`)
      .join("<br>");
  }
  if (policy.bodyRoutes) return `${policy.bodyRoutes.length} strict path-specific JSON contracts`;
  return "**MISSING**";
}

const rows = apiRoutePolicies.map((policy) => {
  const rate = policy.rateLimit ? `${policy.rateLimit.limit} / ${Math.round(policy.rateLimit.windowMs / 1000)}s` : "—";
  return `| \`${policy.id}\` | ${routeExpression(policy)} | ${policy.methods.map((method) => `\`${method}\``).join(" ")} | \`${policy.auth}\` | ${bodyDescription(policy)} | ${rate} |`;
});
const authRows = Object.entries(authDescriptions).map(([mode, description]) => `| \`${mode}\` | ${description} |`);
const generated = `# HTTP API and Authorization Inventory

<!-- Generated by scripts/generate-api-reference.mjs. Do not edit manually. -->

This inventory is generated from the route-policy registry used by the server.
The central boundary rejects unregistered API routes, unsupported methods,
failed authentication, and exhausted shared rate limits before route handlers
run. Handler-level authorization remains explicit where a route needs a wallet,
resource membership, or other context beyond a generic identity class.

## Authentication modes

| Mode | Central contract |
| --- | --- |
${authRows.join("\n")}

## Routes

| Policy | Path matcher | Methods | Authentication | Mutation body | Shared limit |
| --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

Total: **${apiRoutePolicies.length} route policies** and **${Object.keys(authDescriptions).length} authentication modes**.
`;

if (process.argv.includes("--write")) {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${path.relative(root, outputPath)}: ${apiRoutePolicies.length} policies`);
} else {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) throw new Error("api_reference_is_stale; run npm run api-reference-write");
  console.log(`API reference ok: ${apiRoutePolicies.length} policies match the generated inventory`);
}
