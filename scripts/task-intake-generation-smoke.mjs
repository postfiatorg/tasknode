import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Wallet } from "xrpl";

const store = await mkdtemp(join(tmpdir(), "task-intake-smoke-"));
process.env.TASKNODE_STORE_PATH = join(store, "runtime.json");
process.env.TASKNODE_AUTHORITY_SEED = Wallet.generate().seed;
process.env.TASKNODE_TASKGEN_PROVIDER_MOCK = "true";
process.env.TASKNODE_OFFCHAIN_TASK_LIFECYCLE = "true";
process.env.TASKNODE_OFFCHAIN_TASK_LIFECYCLE_DUAL_WRITE = "false";
process.env.TASKNODE_PROCESS_ROLE = "web";
const { closePool, databaseEnabled, query } = await import("../server/db/pool.js");
const { migrateDatabase } = await import("../server/db/migrate.js");
const { saveContextDocument } = await import("../server/repositories/context.js");
const { getOwnedTaskRequest } = await import("../server/repositories/task-requests.js");
const { terminalTaskRequestAction, taskRequestAction } = await import("../server/task-request.js");
const { processTaskGenerationQueueOnce, scheduleTaskGenerationQueue } = await import("../server/task-generation-worker.js");
const accountId = `intake_smoke_${randomUUID()}`;
const otherId = `${accountId}_other`;
assert.ok(databaseEnabled(), "Use an isolated fixture database");
try {
  await migrateDatabase();
  await query("INSERT INTO account_linked_wallets(account_id,wallet_address) VALUES($1,$2)", [accountId, Wallet.generate().classicAddress]);
  await saveContextDocument({ accountId, title: "Personal direction", body: "<p>MY_CONTEXT: Build and document an accessible local task dashboard.</p>" });
  await saveContextDocument({ accountId: otherId, title: "Other account", body: "<p>OTHER_ACCOUNT_PRIVATE_CONTEXT</p>" });
  const payload = { idempotencyKey: "disconnect-retry", userDetailText: "Help me advance my dashboard", source: "pfterminal" };
  const config = await taskRequestAction({ ...payload, phase: "config" }, "POST", { accountId });
  assert.equal(config.status, 200, "direct intake config needs no encryption RPC");
  assert.equal(config.body.offchainLifecycle.writeSource, "direct_write");
  const receipt = await terminalTaskRequestAction(payload, "POST", { accountId });
  assert.equal(receipt.status, 200, JSON.stringify(receipt.body));
  assert.equal(receipt.body.visibleRequest.request.status, "queued");
  assert.equal(receipt.body.visibleRequest.request.metadata.contextEnrichmentPending, true);
  assert.equal(scheduleTaskGenerationQueue({ enabled: true }).reason, "worker_poll_owned_queue");
  const forbidden = await terminalTaskRequestAction({ ...payload, requestedTaskKind: "network" }, "POST", { accountId });
  assert.equal(forbidden.body.error, "task_request_board_allocation_required");
  const result = await processTaskGenerationQueueOnce();
  assert.equal(result.results[0]?.ok, true, JSON.stringify(result));
  const ready = await getOwnedTaskRequest({ accountId, requestId: receipt.body.requestId });
  assert.equal(ready.status, "proposed");
  assert.ok(ready.generatedTaskId);
  assert.equal(ready.metadata.contextEnrichmentPending, false);
  assert.ok(ready.metadata.requestBundle.context.primary_context_doc.summary.includes("MY_CONTEXT"));
  assert.equal(JSON.stringify(ready.metadata.requestBundle).includes("OTHER_ACCOUNT_PRIVATE_CONTEXT"), false);
  assert.ok(ready.metadata.workerResult.timing.totalProcessingMs >= 0);
  assert.equal((await query("SELECT 1 FROM task_events WHERE task_id=$1", [ready.generatedTaskId])).rowCount, 1);
  assert.equal((await query("SELECT 1 FROM task_projections WHERE task_id=$1", [ready.generatedTaskId])).rowCount, 1);
  const replay = await taskRequestAction({ ...payload, phase: "submit" }, "POST", { accountId });
  assert.equal(replay.body.visibleRequest.request.generatedTaskId, ready.generatedTaskId);
  assert.equal((await processTaskGenerationQueueOnce()).claimed, 0);
  console.log(JSON.stringify({ ok: true, sharedWebTerminalReceipt: true, stages: ["queued", "context_enriched", "offer_event", "projection", "receipt_proposed"], provider: "mock", noLedgerPayment: true }));
} finally {
  const ids = [accountId, otherId];
  await query("DELETE FROM task_events WHERE account_id=ANY($1::text[])", [ids]);
  await query("DELETE FROM task_projections WHERE account_id=ANY($1::text[])", [ids]);
  await query("DELETE FROM taskgen_replay_cache WHERE request_id IN (SELECT request_id FROM task_requests WHERE account_id=$1)", [accountId]);
  await query("DELETE FROM task_requests WHERE account_id=$1", [accountId]);
  await query("DELETE FROM account_linked_wallets WHERE account_id=$1", [accountId]);
  await query("DELETE FROM context_revisions WHERE account_id=ANY($1::text[])", [ids]);
  await query("DELETE FROM context_documents WHERE account_id=ANY($1::text[])", [ids]);
  await closePool();
  await rm(store, { recursive: true, force: true });
}
